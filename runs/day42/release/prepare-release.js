const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const { installPackage } = require('../../../scripts/lib/study-template');
const root = path.resolve(__dirname, '../../..');
const sha = bytes => crypto.createHash('sha256').update(bytes).digest('hex');
const read = name => fs.readFileSync(path.join(root, name));
const accepted = JSON.parse(read('runs/day42/release/accepted-artifact-hashes.json'));
for (const [name, hash] of Object.entries(accepted)) assert.equal(sha(read(name)), hash, name);
const remote = JSON.parse(read('runs/day42/release/server-before.json'));
for (const name of ['app.js', 'library/index.html', 'html/assets/fitness-study-logo-open-circle.svg']) {
  assert.equal(sha(read(name)), remote.files[name].sha256, `Local/live drift: ${name}`);
}
const lesson = JSON.parse(read('runs/day42/lesson.json'));
lesson.xhs.caption = lesson.xhs.caption.replace(/\n*本期为本地待验收草稿，尚未发布公开学习链接。\s*$/, '').trimEnd();
assert.ok(!lesson.xhs.caption.includes('尚未发布'));
const isolated = path.join(__dirname, 'staged-site');
const installed = installPackage(lesson, path.join(root, 'runs/day42/revision-05/stage'), isolated);
for (const [name, hash] of Object.entries(accepted)) assert.equal(sha(fs.readFileSync(path.join(isolated, name))), hash, name);
fs.writeFileSync(path.join(__dirname, 'published-lesson.json'), JSON.stringify(lesson, null, 2) + '\n');
const shortlink = 'go/42/index.html';
fs.mkdirSync(path.join(root, 'go/42'), {recursive:true});
fs.copyFileSync(path.join(isolated, shortlink), path.join(root, shortlink));
let app = read('app.js').toString();
assert.ok(!app.includes('publishedPages.set(42,'));
const line = app.split('\n').find(line => line.startsWith('publishedPages.set(41,'));
assert.ok(line);
const encodedPath = JSON.stringify(installed.paths.html).replace(/[\u0080-\uffff]/g, c => '\\u' + c.charCodeAt(0).toString(16).padStart(4, '0'));
app = app.replace(line, line + `\npublishedPages.set(42, ${encodedPath});`);
const thumb = '  [41, "html/thumbs/day41-lower-body-barbell-technique-thumbnail.png"],';
assert.ok(app.includes(thumb));
app = app.replace(thumb, thumb + `\n  [42, ${JSON.stringify(installed.paths.thumbnail)}],`);
fs.writeFileSync(path.join(root, 'app.js'), app);
let library = read('library/index.html').toString();
const script = /app\.js\?v=[a-f0-9]+/g;
assert.equal([...library.matchAll(script)].length, 1);
library = library.replace(script, `app.js?v=${sha(Buffer.from(app)).slice(0,12)}`);
fs.writeFileSync(path.join(root, 'library/index.html'), library);
console.log('Approved images and HTML preserved; staged publication metadata, shortlink, and catalog prepared.');
